/*  server.pl  --  HTTP server that connects the website to hanoi.pl
    Start with:   swipl server.pl
    Then open:    http://localhost:8080
*/

:- use_module(library(http/thread_httpd)).
:- use_module(library(http/http_dispatch)).
:- use_module(library(http/http_files)).
:- use_module(library(http/http_json)).
:- use_module(library(http/http_parameters)).
:- use_module(library(http/json)).
:- use_module(library(lists)).
:- use_module(hanoi).

% Folder that holds index.html, style.css, app.js (relative to this file)
:- dynamic public_dir/1.
:- prolog_load_context(directory, Dir),
   directory_file_path(Dir, public, Public),
   assertz(public_dir(Public)).

/* ---------- Routes ---------- */
:- http_handler(root(api/new),   handle_new,   []).   % GET  /api/new?disks=N
:- http_handler(root(api/solve), handle_solve, []).   % GET  /api/solve?disks=N
:- http_handler(root(api/move),  handle_move,  []).   % POST /api/move  (JSON body)
:- http_handler(root(.), serve_static, [prefix]).     % static site

serve_static(Request) :-
    public_dir(Dir),
    http_reply_from_files(Dir, [], Request).

/* ---------- Start / stop ---------- */

%% start(+Port)  start the web server
start(Port) :-
    http_server(http_dispatch, [port(Port)]),
    format("~n=== Tower of Hanoi server running ===~n"),
    format("Open your browser at:  http://localhost:~w~n", [Port]),
    format("Type  halt.  and press Enter to stop.~n~n").

start :- start(8080).

% Local use  : `swipl server.pl`  -> starts on port 8080 and gives a ?- prompt.
% Cloud (Render): the PORT environment variable is set, so we use that port
%                and keep the process alive (no keyboard is attached there).
:- initialization(boot).

boot :-
    (   getenv('PORT', PortAtom)
    ->  atom_number(PortAtom, Port),
        http_server(http_dispatch, [port(Port)]),
        format("Tower of Hanoi server listening on port ~w~n", [Port]),
        thread_get_message(never_arrives)      % block forever
    ;   start
    ).

/* ---------- Helpers: tower order conversion ----------
   Prolog keeps towers TOP-first; the browser draws BOTTOM-first. */
to_json_state(S, J) :- maplist(reverse, S, J).
from_json_state(J, S) :- maplist(reverse, J, S).

/* ---------- Handlers ---------- */

% New game: initial state + minimum move count (both computed by Prolog)
handle_new(Request) :-
    http_parameters(Request, [disks(N, [integer, between(1, 10)])]),
    initial_state(N, S),
    min_moves(N, Min),
    to_json_state(S, J),
    reply_json_dict(_{disks: N, state: J, minMoves: Min}).

% Full optimal solution: list of moves, generated by Prolog
handle_solve(Request) :-
    http_parameters(Request, [disks(N, [integer, between(1, 10)])]),
    hanoi_moves(N, Moves),
    min_moves(N, Min),
    maplist(move_dict, Moves, MoveDicts),
    reply_json_dict(_{disks: N, minMoves: Min, moves: MoveDicts}).

move_dict(move(D, F, T), _{disk: D, from: F, to: T}).

% Validate and apply one manual move. Body: {"state":[[..],[..],[..]],"from":0,"to":1,"disks":3}
handle_move(Request) :-
    http_read_json_dict(Request, In),
    from_json_state(In.state, S0),
    try_move(S0, In.from, In.to, S, Result),
    to_json_state(S, J),
    (   Result == ok
    ->  ( solved(S, In.disks) -> Done = true ; Done = false ),
        reply_json_dict(_{valid: true, state: J, solved: Done})
    ;   Result = error(Code),
        reason_message(Code, Msg),
        reply_json_dict(_{valid: false, state: J, solved: false,
                          reason: Code, message: Msg})
    ).
